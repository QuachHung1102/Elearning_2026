import { HttpException, type HttpStatus } from '@nestjs/common';

export const ERROR_CODE = {
  VALIDATION_FAILED: 'VALIDATION_FAILED',
  TOKEN_INVALID: 'TOKEN_INVALID',
  ORDER_MISMATCH: 'ORDER_MISMATCH',
  UNAUTHENTICATED: 'UNAUTHENTICATED',
  INVALID_CREDENTIALS: 'INVALID_CREDENTIALS',
  CSRF_INVALID: 'CSRF_INVALID',
  NOT_ENROLLED: 'NOT_ENROLLED',
  EMAIL_NOT_VERIFIED: 'EMAIL_NOT_VERIFIED',
  SIGNATURE_INVALID: 'SIGNATURE_INVALID',
  NOT_FOUND: 'NOT_FOUND',
  EMAIL_TAKEN: 'EMAIL_TAKEN',
  ALREADY_ENROLLED: 'ALREADY_ENROLLED',
  COURSE_HAS_ENROLLMENTS: 'COURSE_HAS_ENROLLMENTS',
  SECTION_NOT_EMPTY: 'SECTION_NOT_EMPTY',
  CATEGORY_NOT_EMPTY: 'CATEGORY_NOT_EMPTY',
  CONFLICT: 'CONFLICT',
  SLUG_TAKEN: 'SLUG_TAKEN',
  EXTERNAL_ID_TAKEN: 'EXTERNAL_ID_TAKEN',
  VIDEO_ALREADY_ATTACHED: 'VIDEO_ALREADY_ATTACHED',
  VIDEO_NOT_READY: 'VIDEO_NOT_READY',
  PAYMENT_EXPIRED: 'PAYMENT_EXPIRED',
  PURCHASE_NOT_REFUNDABLE: 'PURCHASE_NOT_REFUNDABLE',
  SELF_ACTION_FORBIDDEN: 'SELF_ACTION_FORBIDDEN',
  PAYLOAD_TOO_LARGE: 'PAYLOAD_TOO_LARGE',
  UNSUPPORTED_MEDIA_TYPE: 'UNSUPPORTED_MEDIA_TYPE',
  COURSE_NOT_PURCHASABLE: 'COURSE_NOT_PURCHASABLE',
  COURSE_NOT_PUBLISHABLE: 'COURSE_NOT_PUBLISHABLE',
  RATE_LIMITED: 'RATE_LIMITED',
  INTERNAL: 'INTERNAL',
} as const;

export type ErrorCode = (typeof ERROR_CODE)[keyof typeof ERROR_CODE];

export function appError(
  status: HttpStatus,
  code: ErrorCode,
  message: string,
  details?: object,
): HttpException {
  return new HttpException(
    { code, message, ...(details === undefined ? {} : { details }) },
    status,
  );
}
